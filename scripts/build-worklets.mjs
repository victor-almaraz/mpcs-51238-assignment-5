#!/usr/bin/env node
// Bundles src/audio/fx/worklet.js and its imports into public/worklets/fx-chain.js, a single
// AudioWorklet module without import statements (doc/audio/audioworklet.md, Module format).
// Each ES module is converted with Sucrase's `imports` transform and wrapped in a function, so
// module-level names never collide. Successful runs print nothing.
//
// Usage: node scripts/build-worklets.mjs [--check]
//   --check  fails when public/worklets/fx-chain.js differs from a fresh build, instead of writing it

import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'sucrase';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BUNDLES = [
  { entry: 'src/audio/fx/worklet.js', out: 'public/worklets/fx-chain.js', name: 'fx-chain' },
];

/** @param {string} msg */
function die(msg) {
  process.stderr.write(`${JSON.stringify({ level: 'error', event: 'build_worklets', message: msg })}\n`);
  process.exit(1);
}

/** @param {string} spec @param {string} fromDir */
function resolveSpec(spec, fromDir) {
  if (!spec.startsWith('.')) die(`${relative(ROOT, fromDir)}: worklet modules may import only relative paths, not ${spec}`);
  const base = resolve(fromDir, spec);
  for (const c of [base, `${base}.js`]) if (existsSync(c) && statSync(c).isFile()) return c;
  die(`cannot resolve ${spec} from ${relative(ROOT, fromDir)}`);
  return '';
}

/** @param {string} entryRel */
function bundle(entryRel) {
  const entry = join(ROOT, entryRel);
  /** @type {Map<string, { id: number, code: string, deps: Record<string, number> }>} */
  const mods = new Map();
  const queue = [];
  const idOf = (/** @type {string} */ file) => {
    if (!mods.has(file)) { mods.set(file, { id: mods.size, code: '', deps: {} }); queue.push(file); }
    return /** @type {{ id: number }} */ (mods.get(file)).id;
  };
  idOf(entry);
  while (queue.length) {
    const file = /** @type {string} */ (queue.shift());
    const mod = /** @type {any} */ (mods.get(file));
    mod.code = transform(readFileSync(file, 'utf8'), { transforms: ['imports'], filePath: file }).code;
    for (const m of mod.code.matchAll(/\brequire\((['"])([^'"\n]+)\1\)/g)) {
      if (!(m[2] in mod.deps)) mod.deps[m[2]] = idOf(resolveSpec(m[2], dirname(file)));
    }
  }
  const entries = [...mods.entries()].map(([file, m]) => {
    const name = relative(ROOT, file).split('\\').join('/');
    return `/* ${name} */ [function (module, exports, require) {\n${m.code}\n}, ${JSON.stringify(m.deps)}]`;
  });
  return `// Generated by scripts/build-worklets.mjs from ${entryRel}. Do not edit.
(function () {
  'use strict';
  var defs = [
${entries.join(',\n')}
  ];
  var cache = [];
  function load(id) {
    if (cache[id]) return cache[id].exports;
    var module = { exports: {} };
    cache[id] = module;
    var deps = defs[id][1];
    defs[id][0].call(module.exports, module, module.exports, function (spec) { return load(deps[spec]); });
    return module.exports;
  }
  load(0);
})();
`;
}

const check = process.argv.includes('--check');
for (const b of BUNDLES) {
  const code = bundle(b.entry);
  const out = join(ROOT, b.out);
  if (check) {
    if (!existsSync(out) || readFileSync(out, 'utf8') !== code) die(`${b.out} is out of date; run node scripts/build-worklets.mjs`);
  } else {
    writeFileSync(out, code);
  }
}
