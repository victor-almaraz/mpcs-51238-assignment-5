#!/usr/bin/env node
// Bundles src/audio/fx/worklet.js and its imports into public/worklets/fx-chain.js, a single
// AudioWorklet module without import statements (doc/audio/audioworklet.md, Module format).
// Each ES module is converted with Sucrase's `imports` transform and wrapped in a function, so
// module-level names never collide. Successful runs print nothing.
//
// Usage: node scripts/build-worklets.mjs [--check]
//   --check  fails when public/worklets/fx-chain.js differs from a fresh build, instead of writing it

import { existsSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundle, esToCommonJs } from './lib/bundle.mjs';
import { fail, parseArgs, writeOrCheck } from './lib/cli.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const EVENT = 'build_worklets';
const USAGE = 'node scripts/build-worklets.mjs [--check]';
const BUNDLES = [
  { entry: 'src/audio/fx/worklet.js', out: 'public/worklets/fx-chain.js', name: 'fx-chain' },
];

/** Worklet modules import only relative paths. @param {string} spec @param {string} fromDir */
function resolveSpec(spec, fromDir) {
  if (!spec.startsWith('.')) fail(EVENT, `${relative(ROOT, fromDir)}: worklet modules may import only relative paths, not ${spec}`);
  const base = resolve(fromDir, spec);
  for (const c of [base, `${base}.js`]) if (existsSync(c) && statSync(c).isFile()) return c;
  return fail(EVENT, `cannot resolve ${spec} from ${relative(ROOT, fromDir)}`);
}

const { check } = parseArgs(process.argv.slice(2), { check: 'boolean' }, USAGE, EVENT);
try {
  for (const b of BUNDLES) {
    const code = bundle({
      root: ROOT, entry: join(ROOT, b.entry), load: esToCommonJs, resolve: resolveSpec,
      header: `// Generated by scripts/build-worklets.mjs from ${b.entry}. Do not edit.`,
    });
    if (!writeOrCheck(join(ROOT, b.out), code, check)) fail(EVENT, `${b.out} is out of date; run node scripts/build-worklets.mjs`);
  }
} catch (err) {
  fail(EVENT, /** @type {Error} */ (err).message);
}
