#!/usr/bin/env node
// Generates the type-check inputs from the definition tables (doc/piece-dsl.md, Types):
//   src/dsl/builder.d.ts     global builder API types
//   src/dsl/builder-dts.js   the same text as a module, bundled into the type-check worker
//   src/dsl/ts-lib-files.js  the ES2022 library declarations, bundled into the type-check worker
// Output depends only on the tables and the installed TypeScript, so runs are deterministic.
// Successful runs print nothing.
//
// Usage: node scripts/gen-builder-dts.mjs [--defs <module>]... [--check]
//   --check  fails when a file differs from a fresh generation, instead of writing it

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { diag, loadDefs } from './lib/defs.mjs';
import { generateBuilderDts } from '../src/dsl/gen-dts.js';
import { libClosure } from '../src/dsl/typecheck.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);

try {
  const defs = await loadDefs(ROOT, argv);
  const dts = generateBuilderDts(defs);
  const tsLib = dirname(createRequire(import.meta.url).resolve('typescript/lib/typescript.js'));
  const libs = libClosure((name) => readFileSync(join(tsLib, name), 'utf8'));
  const header = '// Generated by scripts/gen-builder-dts.mjs. Do not edit.\n';
  const files = {
    'src/dsl/builder.d.ts': dts,
    'src/dsl/builder-dts.js': `${header}export default ${JSON.stringify(dts)};\n`,
    'src/dsl/ts-lib-files.js': `${header}// TypeScript library declarations (Apache-2.0, Microsoft) for the type-check worker.\nexport default {\n${
      Object.entries(libs).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}\n};\n`,
  };
  const check = argv.includes('--check');
  for (const [rel, text] of Object.entries(files)) {
    const file = join(ROOT, rel);
    if (check) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== text) {
        diag({ level: 'error', event: 'gen_builder_dts', file: rel, message: 'out of date; run node scripts/gen-builder-dts.mjs' });
        process.exitCode = 1;
      }
    } else {
      writeFileSync(file, text);
    }
  }
} catch (e) {
  diag({ level: 'error', event: 'gen_builder_dts', message: /** @type {Error} */ (e).message });
  process.exitCode = 1;
}
