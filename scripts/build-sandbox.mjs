#!/usr/bin/env node
// Bundles src/dsl/sandbox-entry.js and its dependencies (the DSL modules and Sucrase) into
// public/dsl-sandbox.js, a single script without import or export statements that loads as a
// classic or a module worker. The bundler is a small CommonJS linker: ES modules are converted
// with Sucrase's `imports` transform, JSON files become `module.exports = ...`, and package
// requires resolve through each package's `main`. Successful runs print nothing.
//
// Usage: node scripts/build-sandbox.mjs [--check]
//   --check  fails when public/dsl-sandbox.js differs from a fresh build, instead of writing it

import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'sucrase';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = join(ROOT, 'src/dsl/sandbox-entry.js');
const OUT = join(ROOT, 'public/dsl-sandbox.js');

/** Packages Sucrase requires only for source maps and token debugging, which the sandbox never uses. */
const STUBS = new Set(['@jridgewell/gen-mapping', 'lines-and-columns']);

/** @param {string} msg */
function die(msg) {
  process.stderr.write(`${JSON.stringify({ level: 'error', event: 'build_sandbox', message: msg })}\n`);
  process.exit(1);
}

/** @param {string} p */
const isFile = (p) => existsSync(p) && statSync(p).isFile();

/** @param {string} spec @param {string} fromDir @returns {string | null} */
function resolveSpec(spec, fromDir) {
  if (spec.startsWith('.') || spec.startsWith('/')) {
    const base = resolve(fromDir, spec);
    for (const c of [base, `${base}.js`, `${base}.json`, join(base, 'index.js')]) if (isFile(c)) return c;
    return null;
  }
  const parts = spec.split('/');
  const pkgName = spec.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
  const sub = parts.slice(spec.startsWith('@') ? 2 : 1).join('/');
  for (let dir = fromDir; ; dir = dirname(dir)) {
    const pkgDir = join(dir, 'node_modules', pkgName);
    if (existsSync(join(pkgDir, 'package.json'))) {
      if (sub) return resolveSpec(`./${sub}`, pkgDir);
      const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
      return resolveSpec(`./${pkg.main ?? 'index.js'}`, pkgDir);
    }
    if (dir === dirname(dir)) return null;
  }
}

/** @param {string} file @returns {string} CommonJS source */
function load(file) {
  const text = readFileSync(file, 'utf8');
  if (file.endsWith('.json')) return `module.exports = ${JSON.stringify(JSON.parse(text))};`;
  if (file.includes(`${'/'}node_modules${'/'}`)) return text;
  return transform(text, { transforms: ['imports'], filePath: file }).code;
}

function bundle() {
  /** @type {Map<string, { id: number, code: string, deps: Record<string, number | null> }>} */
  const mods = new Map();
  /** @type {string[]} */
  const queue = [];
  /** @param {string} file */
  const idOf = (file) => {
    if (!mods.has(file)) {
      mods.set(file, { id: mods.size, code: '', deps: {} });
      queue.push(file);
    }
    return /** @type {{ id: number }} */ (mods.get(file)).id;
  };
  idOf(ENTRY);
  while (queue.length) {
    const file = /** @type {string} */ (queue.shift());
    const mod = /** @type {any} */ (mods.get(file));
    mod.code = load(file);
    for (const m of mod.code.matchAll(/\brequire\((['"])([^'"\n]+)\1\)/g)) {
      const spec = m[2];
      if (spec in mod.deps) continue;
      if (STUBS.has(spec)) { mod.deps[spec] = -1; continue; }
      const target = resolveSpec(spec, dirname(file));
      // Unresolvable requires occur only in Sucrase's comments and unused CLI paths.
      mod.deps[spec] = target ? idOf(target) : null;
    }
  }
  const entries = [...mods.entries()].map(([file, m]) => {
    const name = relative(ROOT, file).split('\\').join('/');
    return `/* ${name} */ [function (module, exports, require) {\n${m.code}\n}, ${JSON.stringify(m.deps)}]`;
  });
  return `// Generated by scripts/build-sandbox.mjs from src/dsl/sandbox-entry.js. Do not edit.
// Sandbox worker for piece scripts (doc/piece-dsl.md, Sandbox). Bundles Sucrase (MIT, Alan Pierce)
// and ts-interface-checker (Apache-2.0, Grist Labs).
(function () {
  'use strict';
  var defs = [
${entries.join(',\n')}
  ];
  var cache = [];
  function load(id) {
    if (cache[id]) return cache[id].exports;
    var module = { exports: {} };
    cache[id] = module;
    var deps = defs[id][1];
    defs[id][0].call(module.exports, module, module.exports, function (spec) {
      var dep = deps[spec];
      if (dep === -1) return {};
      if (dep === null || dep === undefined) throw new Error('dsl-sandbox: module ' + spec + ' is not bundled');
      return load(dep);
    });
    return module.exports;
  }
  load(0);
})();
`;
}

const code = bundle();
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== code) die('public/dsl-sandbox.js is out of date; run node scripts/build-sandbox.mjs');
} else {
  writeFileSync(OUT, code);
}
