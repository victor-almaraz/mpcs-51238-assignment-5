#!/usr/bin/env node
// Bundles src/dsl/sandbox-entry.js and its dependencies (the DSL modules and Sucrase) into
// public/dsl-sandbox.js, a single script without import or export statements that loads as a
// classic or a module worker. The bundler is a small CommonJS linker: ES modules are converted
// with Sucrase's `imports` transform, JSON files become `module.exports = ...`, and package
// requires resolve through each package's `main`. Successful runs print nothing.
//
// Usage: node scripts/build-sandbox.mjs [--check]
//   --check  fails when public/dsl-sandbox.js differs from a fresh build, instead of writing it

import { existsSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundle, esToCommonJs } from './lib/bundle.mjs';
import { fail, parseArgs, writeOrCheck } from './lib/cli.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = join(ROOT, 'src/dsl/sandbox-entry.js');
const OUT = join(ROOT, 'public/dsl-sandbox.js');
const EVENT = 'build_sandbox';
const USAGE = 'node scripts/build-sandbox.mjs [--check]';

/** Packages Sucrase requires only for source maps and token debugging, which the sandbox never uses. */
const STUBS = new Set(['@jridgewell/gen-mapping', 'lines-and-columns']);

/** @param {string} p */
const isFile = (p) => existsSync(p) && statSync(p).isFile();

/** @param {string} spec @param {string} fromDir @returns {string | null} */
function resolveFile(spec, fromDir) {
  if (spec.startsWith('.') || spec.startsWith('/')) {
    const base = resolve(fromDir, spec);
    for (const c of [base, `${base}.js`, `${base}.json`, join(base, 'index.js')]) if (isFile(c)) return c;
    return null;
  }
  const parts = spec.split('/');
  const pkgName = spec.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
  const sub = parts.slice(spec.startsWith('@') ? 2 : 1).join('/');
  for (let dir = fromDir; ; dir = dirname(dir)) {
    const pkgDir = join(dir, 'node_modules', pkgName);
    if (existsSync(join(pkgDir, 'package.json'))) {
      if (sub) return resolveFile(`./${sub}`, pkgDir);
      const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
      return resolveFile(`./${pkg.main ?? 'index.js'}`, pkgDir);
    }
    if (dir === dirname(dir)) return null;
  }
}

/** Unresolvable requires occur only in Sucrase's comments and unused CLI paths. @param {string} spec @param {string} fromDir */
const resolveSpec = (spec, fromDir) => (STUBS.has(spec) ? -1 : resolveFile(spec, fromDir));

/** @param {string} file @returns {string} CommonJS source */
function load(file) {
  if (file.endsWith('.json')) return `module.exports = ${JSON.stringify(JSON.parse(readFileSync(file, 'utf8')))};`;
  if (file.includes(`${'/'}node_modules${'/'}`)) return readFileSync(file, 'utf8');
  return esToCommonJs(file);
}

const { check } = parseArgs(process.argv.slice(2), { check: 'boolean' }, USAGE, EVENT);
try {
  const code = bundle({
    root: ROOT, entry: ENTRY, load, resolve: resolveSpec,
    header: `// Generated by scripts/build-sandbox.mjs from src/dsl/sandbox-entry.js. Do not edit.
// Sandbox worker for piece scripts (doc/piece-dsl.md, Sandbox). Bundles Sucrase (MIT, Alan Pierce)
// and ts-interface-checker (Apache-2.0, Grist Labs).`,
  });
  if (!writeOrCheck(OUT, code, check)) fail(EVENT, 'public/dsl-sandbox.js is out of date; run node scripts/build-sandbox.mjs');
} catch (err) {
  fail(EVENT, /** @type {Error} */ (err).message);
}
